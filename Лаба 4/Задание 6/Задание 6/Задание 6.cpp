#include <iostream>
#include <string>
#include <vector>
#include <iomanip>
using namespace std;

int main() {
    setlocale(LC_ALL, "Russian");
    int n;
    cout << "Введите количество товаров: ";
    cin >> n;

    vector<int> A(n);
    vector<string> S(n);

    for (int i = 0; i < n; i++) {
        cout << "Введите название товара " << (i + 1) << ": ";
        cin >> S[i];
        cout << "Введите цену товара " << (i + 1) << ": ";
        cin >> A[i];
    }

    int s = 0;
    int i = 0;

    cout << "\nЧек (до суммы 500 коп):" << endl;
    cout << "=========================" << endl;
    while (i < n && s <= 500) {
        cout << setw(20) << left << S[i] << " - " << A[i] << " коп." << endl;
        s = s + A[i];
        i = i + 1;
    }
    cout << "=========================" << endl;
    cout << "Итоговая сумма: " << s << " коп." << endl;
    return 0;
}

